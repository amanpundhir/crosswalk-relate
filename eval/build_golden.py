"""Generate eval/golden_questions.yaml from the oracle (expected answers are never typed by hand).

    python -I eval/build_golden.py

Node ids used in ``must_cite``: requirements ``800-53:AC-2``, controls ``CTRL-...``, evidence ``EV-...``,
people ``P-...``, audits ``AUD-...``, proposals ``PR-...``, decisions ``D-...``, frameworks ``800-53`` /
``800-171`` / ``CSF``.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import oracle as o  # noqa: E402
import yaml  # noqa: E402

OUT = o.REPO / "eval" / "golden_questions.yaml"

HEADER = """\
# 20 golden questions, asked the way Maya Chen (security lead, Harbor & Pine, fictional) would ask them.
# GENERATED by eval/build_golden.py from eval/oracle.py (as_of 2026-12-02). Do not edit by hand.
# expected   machine-checkable answer from the oracle (numbers and id sets)
# must_cite  node ids that must appear in the cited paths of a correct answer
# trap       planted scenario probed (S1..S8, see eval/planted.yaml) or null
"""


def build() -> list[dict]:
    w = o.world()
    cov = o.q1_coverage()["by_framework"]
    c171, c53, ccsf = cov["800-171"], cov["800-53"], cov["CSF"]
    audits = o.q1_coverage()["by_audit"]
    b30 = o.blast(30)
    b171 = o.blast(until=w["audits"]["AUD-171"]["date"])
    risk = o.q6_owner_risk()
    dana = risk["people"]["P-dana-okafor"]
    reuse = o.q4_reuse()
    top = reuse[0]
    e0301 = o.explain("800-171:03.03.01")
    stale = o.legacy_stale()
    decoy = [d for d in o.decoys() if d["evidence"] == "EV-103"][0]
    rej = o.rejections()
    b_still = [b["requirement"] for b in b171["broken_requirements"]
               if b["framework"] == "800-171" and b["still_inherited"]]
    b_not = [b["requirement"] for b in b171["broken_requirements"]
             if b["framework"] == "800-171" and not b["still_inherited"]]

    def q(id_, question, expected, must_cite, trap=None):
        return {"id": id_, "question": question, "expected": expected,
                "must_cite": sorted(must_cite), "trap": trap}

    out = [
        q("GQ-01", "What share of NIST 800-171 do we cover today, directly and counting what we inherit from our 800-53 work?",
          {"active_requirements": 97, "direct": c171["counts"]["direct"], "inherited": c171["counts"]["inherited"],
           "gap": c171["counts"]["gap"], "percent_direct": c171["percent_direct"],
           "percent_direct_plus_inherited": c171["percent_direct_plus_inherited"]},
          ["800-171"]),
        q("GQ-02", "How is our 800-53 coverage looking? How many requirements do we cover and how many are gaps?",
          {"active_requirements": c53["active_requirements"], "direct": c53["counts"]["direct"],
           "inherited": 0, "gap": c53["counts"]["gap"], "percent_direct": c53["percent_direct"]},
          ["800-53"]),
        q("GQ-03", "If we adopted CSF 2.0 tomorrow, how many subcategories would we already meet through the crosswalk?",
          {"active_requirements": ccsf["active_requirements"], "direct": ccsf["counts"]["direct"],
           "inherited": ccsf["counts"]["inherited"], "gap": ccsf["counts"]["gap"],
           "percent_direct_plus_inherited": ccsf["percent_direct_plus_inherited"]},
          ["CSF"], "S5"),
        q("GQ-04", "Which 800-171 requirements do we meet only through our 800-53 mappings, with no direct 800-171 mapping?",
          {"count": c171["counts"]["inherited"], "requirements": c171["inherited"]},
          ["800-171", "800-53:SC-13", "800-53:SI-3", "800-171:03.13.11", "800-171:03.14.02"], "S5"),
        q("GQ-05", "Our old tracker says MFA is compliant. Is 800-171 03.05.03 actually covered right now?",
          {"covered_direct": False, "inherited": False, "evidence": "EV-044",
           "evidence_expired_at": w["evidence"]["EV-044"]["expires_at"],
           "approved_control_with_valid_evidence": [], "proposed_only_controls": o.proposed_only("800-171:03.05.03")},
          ["800-171:03.05.03", "CTRL-REAP-6", "EV-044", "CTRL-PWP-4", "PR-005"], "S1"),
        q("GQ-06", "Which controls does the legacy tracker mark as Compliant even though they have no valid evidence today?",
          {"controls": [s["control"] for s in stale]},
          [s["control"] for s in stale], "S1"),
        q("GQ-07", "Which evidence expires before the 800-171 assessment on 15 January 2027, and which 800-171 requirements break because of it?",
          {"evidence": [e["evidence"] for e in b171["expiring_evidence"]],
           "broken_800_171_count": b171["broken_counts"]["800-171"],
           "broken_800_171": b171["broken_by_framework"]["800-171"]},
          [e["evidence"] for e in b171["expiring_evidence"]] + ["AUD-171"], "S2"),
        q("GQ-08", "Which audits are affected if the evidence expiring in the next 30 days lapses?",
          {"cutoff": b30["cutoff"], "expiring_evidence": [e["evidence"] for e in b30["expiring_evidence"]],
           "affected_audits": [a["audit"] for a in b30["affected_audits"]],
           "broken_counts": b30["broken_counts"]},
          [e["evidence"] for e in b30["expiring_evidence"]] + [a["audit"] for a in b30["affected_audits"]], "S2"),
        q("GQ-09", "Of the 800-171 requirements that break before the January audit, which are still met through an 800-53 neighbour?",
          {"still_inherited": sorted(b_still), "broken_and_not_inherited": sorted(b_not)},
          sorted(b_still) + sorted(b_not), "S2"),
        q("GQ-10", "On the day of the 800-171 audit, which controls will be left without any valid evidence?",
          {"controls": b171["controls_left_without_valid_evidence"]},
          b171["controls_left_without_valid_evidence"], None),
        q("GQ-11", "EV-103, the incremental backup report, expired on 20 November. Does that put our backup coverage at risk?",
          {"at_risk": False, "control": "CTRL-AP-9", "requirement_still_covered": "800-53:CP-9",
           "valid_replacements": decoy["valid_replacements"],
           "in_blast_30d": "EV-103" in [e["evidence"] for e in b30["expiring_evidence"]],
           "in_blast_until_audit_171": "EV-103" in [e["evidence"] for e in b171["expiring_evidence"]]},
          ["EV-103", "CTRL-AP-9", "800-53:CP-9"] + decoy["valid_replacements"], "S6"),
        q("GQ-12", "Can you map our monthly account review control CTRL-AOTP-11 to AC-17?",
          {"allowed": False, "previously_rejected": True, "decided_by": "P-maya-chen", "decided_at": "2026-11-25",
           "reason": next(r["reason"] for r in rej if r["control"] == "CTRL-AOTP-11")},
          ["CTRL-AOTP-11", "800-53:AC-17", "D-001", "PR-001", "P-maya-chen"], "S4"),
        q("GQ-13", "Which mapping suggestions have we rejected before, and why?",
          {"rejections": [{"control": r["control"], "requirement": r["requirement"], "decided_at": r["decided_at"]}
                          for r in rej]},
          ["D-001", "D-002", "CTRL-AOTP-11", "CTRL-REAP-7"], "S4"),
        q("GQ-14", "Which adopted controls have no owner?",
          {"controls": risk["unowned_controls"]}, risk["unowned_controls"], "S8"),
        q("GQ-15", "How many controls does Dana Okafor solely own, and which high-criticality systems would be left without an owner if she left?",
          {"person": "P-dana-okafor", "sole_owned_count": dana["sole_owned_count"],
           "controls": dana["controls_solely_owned"], "high_criticality_systems": dana["high_criticality_systems"]},
          ["P-dana-okafor"] + dana["controls_solely_owned"], "S3"),
        q("GQ-16", "If Dana left tomorrow, which requirements would lose all their coverage?",
          {"requirements": dana["requirements_solely_dependent"]},
          ["P-dana-okafor"] + dana["requirements_solely_dependent"], "S3"),
        q("GQ-17", "Which single evidence item do we reuse the most, and which frameworks does it reach?",
          {"evidence": top["evidence"], "direct_requirements": top["direct_count"],
           "frameworks_direct": top["frameworks_direct"], "frameworks_reached": top["frameworks_reached"],
           "reach_count_1_hop": top["reach_count"], "requested_by": ["AUD-171", "AUD-53", "AUD-CSF"]},
          [top["evidence"]] + top["controls"], "S7"),
        q("GQ-18", "Which evidence items requested for the 800-171 assessment are already expired?",
          {"evidence": audits["AUD-171"]["requested_evidence_invalid_at_as_of"]},
          ["AUD-171"] + audits["AUD-171"]["requested_evidence_invalid_at_as_of"], None),
        q("GQ-19", "For the internal 800-53 review on 20 February 2027, which requested evidence will be expired by then?",
          {"evidence": audits["AUD-53"]["requested_evidence_invalid_at_audit_date"]},
          ["AUD-53"] + audits["AUD-53"]["requested_evidence_invalid_at_audit_date"], None),
        q("GQ-20", "Show me how 800-171 03.03.01 is covered, with the evidence and its dates.",
          {"covered_direct": e0301["covered_direct"],
           "paths": [{"control": p["control"], "evidence": p["evidence"], "expires_at": p["expires_at"],
                      "valid": p["valid"]} for p in e0301["paths"]]},
          ["800-171:03.03.01"] + sorted({p["control"] for p in e0301["paths"]})
          + sorted({p["evidence"] for p in e0301["paths"]}), None),
    ]
    return out


def render() -> str:
    return HEADER + yaml.safe_dump(build(), sort_keys=False, allow_unicode=True, width=110)


def main() -> int:
    with OUT.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(render())
    print(f"wrote {OUT} ({len(build())} questions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
